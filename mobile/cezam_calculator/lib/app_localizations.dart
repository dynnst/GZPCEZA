import 'package:flutter/widgets.dart';

class AppLocalizations {
  AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = [
    Locale('tr'),
    Locale('en'),
    Locale('ru'),
    Locale('fa'),
    Locale('ar'),
  ];

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  String text(String key) =>
      (_values[locale.languageCode] ?? _values['en']!)[key] ??
      (_extraValues[locale.languageCode] ?? _extraValues['en']!)[key] ??
      (_messageValues[locale.languageCode] ?? _messageValues['en']!)[key] ??
      _values['en']![key] ??
      _extraValues['en']![key] ??
      _messageValues['en']![key] ??
      key;

  String withValue(String key, Object value) =>
      text(key).replaceAll('{value}', value.toString());

  static const delegate = _AppLocalizationsDelegate();
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales.any(
        (item) => item.languageCode == locale.languageCode,
      );

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

extension AppTranslation on BuildContext {
  String tr(String key) => AppLocalizations.of(this).text(key);
  String trValue(String key, Object value) =>
      AppLocalizations.of(this).withValue(key, value);
}

